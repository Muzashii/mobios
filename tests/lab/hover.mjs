import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5173/');
await page.evaluate(() => { indexedDB.deleteDatabase('mobios'); localStorage.setItem('mobios-onboarding-done', '1'); });
await page.reload();
await page.getByTestId('open-example').click();
await page.waitForTimeout(3000);
await page.keyboard.press('s');
const box = await page.getByTestId('viewport').boundingBox();
const head = { x: box.x + box.width * 0.5, y: box.y + box.height * 0.27 };
await page.mouse.move(head.x, head.y);
await page.waitForTimeout(4000);
await page.mouse.move(head.x + 3, head.y + 2);
await page.waitForTimeout(800);
await page.screenshot({ path: process.argv[2] ?? 'hover.png' });
await page.mouse.click(head.x + 3, head.y + 2);
await page.waitForTimeout(6000);
await page.screenshot({ path: (process.argv[2] ?? 'hover.png').replace('.png', '-review.png') });
await browser.close();
