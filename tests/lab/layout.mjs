import { chromium } from '@playwright/test';
// Screenshots of the flow in a fresh browser profile: example → split (all parts) → joints → colours, plus a phone.
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:5173/');
await page.screenshot({ path: `${out}/ui-empty.png` });
await page.getByTestId('open-example').click();
await page.getByTestId('split-all').waitFor({ timeout: 60_000 });
const box = await page.getByTestId('viewport').boundingBox();
await page.mouse.move(box.x + box.width * 0.5, box.y + box.height * 0.27);
await page.waitForTimeout(600);
await page.mouse.move(box.x + box.width * 0.5 + 3, box.y + box.height * 0.27 + 2);
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/ui-split.png` });
await page.getByTestId('cut-menu').click();
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/ui-cutmenu.png` });
await page.keyboard.press('Escape');
const t0 = Date.now();
await page.getByTestId('split-all').click();
await page.getByRole('list', { name: 'Lista de peças' }).getByTestId('part-row').nth(4).waitFor({ timeout: 120_000 }).catch(async () => { await page.screenshot({ path: `${out}/ui-stuck.png` }); console.log(await page.getByLabel('Histórico').innerText()); });
await page.waitForFunction(() => !document.querySelector('[role=status].shimmer'), null, { timeout: 300_000 }).catch(() => {});
await page.waitForTimeout(2000);
console.log('split-all ms', Date.now() - t0);
await page.screenshot({ path: `${out}/ui-after-split.png` });
await page.getByTestId('step-fit').click();
await page.keyboard.press('e');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/ui-fit.png` });
await page.getByTestId('step-color').click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/ui-color.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByTestId('step-split').click();
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/ui-phone.png` });
await browser.close();
